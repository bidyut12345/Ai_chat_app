/**
 * Tests for Sub-Agent, Task Breakdown, Live Steering, and Background Tasks:
 * 1. Built-in MCP servers discovery: `subagent` (2 tools) and `background` (4 tools).
 * 2. Task breakdown planning tool `subagent__plan_tasks` emits task_plan event.
 * 3. Sub-agent execution `subagent__run_task` with scoped workspace and tool execution.
 * 4. Main agent waits synchronously until subagent completes and receives structured summary.
 * 5. Dynamic user steering `POST /api/chat/steer` queues steering directives.
 * 6. Background tasks execution, timer check-back, and REST API endpoints.
 */
import http from 'node:http';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP_PORT = 4890;
const MOCK_PORT = 4891;
const BASE = `http://127.0.0.1:${APP_PORT}`;

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'subagent-test-'));
const dbPath = path.join(tmp, 'test.db');
const workDir = path.join(tmp, 'workspace');
fs.mkdirSync(workDir, { recursive: true });

let passed = 0;
let failed = 0;
function check(label, ok, extra = '') {
  if (ok) {
    passed++;
    console.log(`  ✓ ${label}`);
  } else {
    failed++;
    console.error(`  ✗ ${label}${extra ? `\n      ${String(extra).split('\n').join('\n      ')}` : ''}`);
  }
}

let mockTurn = 0;
let lastReceivedTools = null;

// Mock OpenAI server that simulates main agent and subagent turns
const mockServer = http.createServer((req, res) => {
  if (req.url === '/v1/models') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({ data: [{ id: 'mock-model' }] }));
  }

  if (req.url === '/v1/chat/completions') {
    let body = '';
    req.on('data', (c) => { body += c; });
    req.on('end', () => {
      const parsed = JSON.parse(body);
      const msgs = parsed.messages || [];
      const isSubagent = msgs.some((m) => m.role === 'system' && m.content?.includes('autonomous sub-agent'));

      res.writeHead(200, {
        'Content-Type': 'text/event-stream',
        'Cache-Control': 'no-cache',
        Connection: 'keep-alive'
      });

      if (isSubagent) {
        // Sub-agent turn: calls files__write_file then returns summary
        const hasToolResult = msgs.some((m) => m.role === 'tool');
        if (!hasToolResult) {
          // Sub-agent calls files__write_file
          const tcId = `call_sub_${Date.now()}`;
          const chunk = {
            id: 'mock-sub-1',
            object: 'chat.completion.chunk',
            choices: [{
              index: 0,
              delta: {
                tool_calls: [{
                  index: 0,
                  id: tcId,
                  type: 'function',
                  function: {
                    name: 'files__write_file',
                    arguments: JSON.stringify({ path: 'subagent-output.txt', content: 'Generated by subagent.' })
                  }
                }]
              }
            }]
          };
          res.write(`data: ${JSON.stringify(chunk)}\n\n`);
          res.write('data: [DONE]\n\n');
          return res.end();
        } else {
          // Subagent receives tool result and provides final summary
          const chunk = {
            id: 'mock-sub-2',
            object: 'chat.completion.chunk',
            choices: [{
              index: 0,
              delta: {
                content: 'Successfully verified files and created subagent-output.txt with initial payload.'
              }
            }]
          };
          res.write(`data: ${JSON.stringify(chunk)}\n\n`);
          res.write('data: [DONE]\n\n');
          return res.end();
        }
      }

      // Main agent turns
      mockTurn++;
      if (mockTurn === 1) {
        // Main agent: calls subagent__plan_tasks
        const tcId = `call_plan_${Date.now()}`;
        const chunk = {
          id: 'mock-main-1',
          object: 'chat.completion.chunk',
          choices: [{
            index: 0,
            delta: {
              tool_calls: [{
                index: 0,
                id: tcId,
                type: 'function',
                function: {
                  name: 'subagent__plan_tasks',
                  arguments: JSON.stringify({
                    tasks: [
                      { id: 'step_1', title: 'Analyze & write subagent file', description: 'Creates subagent-output.txt' }
                    ]
                  })
                }
              }]
            }
          }]
        };
        res.write(`data: ${JSON.stringify(chunk)}\n\n`);
        res.write('data: [DONE]\n\n');
        return res.end();
      } else if (mockTurn === 2) {
        // Main agent: calls subagent__run_task for Step 1
        const tcId = `call_run_sub_${Date.now()}`;
        const chunk = {
          id: 'mock-main-2',
          object: 'chat.completion.chunk',
          choices: [{
            index: 0,
            delta: {
              tool_calls: [{
                index: 0,
                id: tcId,
                type: 'function',
                function: {
                  name: 'subagent__run_task',
                  arguments: JSON.stringify({
                    title: 'Step 1: Write File',
                    task: 'Write subagent-output.txt',
                    workspace: 'sub_workspace',
                    tools: ['files']
                  })
                }
              }]
            }
          }]
        };
        res.write(`data: ${JSON.stringify(chunk)}\n\n`);
        res.write('data: [DONE]\n\n');
        return res.end();
      } else {
        // Main agent receives sub-agent summary and gives final response
        const chunk = {
          id: 'mock-main-3',
          object: 'chat.completion.chunk',
          choices: [{
            index: 0,
            delta: {
              content: 'All tasks completed successfully by sub-agent.'
            }
          }]
        };
        res.write(`data: ${JSON.stringify(chunk)}\n\n`);
        res.write('data: [DONE]\n\n');
        return res.end();
      }
    });
    return;
  }

  res.writeHead(404).end();
});

let appProc = null;

async function startAll() {
  await new Promise((r) => mockServer.listen(MOCK_PORT, r));

  appProc = spawn('node', ['server/index.js'], {
    cwd: ROOT,
    env: {
      ...process.env,
      PORT: String(APP_PORT),
      DB_PATH: dbPath,
      AUTH_DISABLED: '1',
      OPENAI_BASE_URL: `http://127.0.0.1:${MOCK_PORT}/v1`,
      OPENAI_MODEL: 'mock-model'
    },
    stdio: 'inherit'
  });

  // Wait for health endpoint
  for (let i = 0; i < 30; i++) {
    try {
      const res = await fetch(`${BASE}/api/health`);
      if (res.ok) return;
    } catch {}
    await new Promise((r) => setTimeout(r, 200));
  }
  throw new Error('App server failed to start within timeout');
}

function cleanup() {
  try { mockServer.close(); } catch {}
  try { if (appProc) appProc.kill('SIGKILL'); } catch {}
  try { fs.rmSync(tmp, { recursive: true, force: true }); } catch {}
}

async function api(endpoint, opts = {}) {
  const url = `${BASE}/api${endpoint}`;
  const res = await fetch(url, {
    headers: { 'Content-Type': 'application/json', ...(opts.headers || {}) },
    ...opts,
    body: opts.body ? (typeof opts.body === 'string' ? opts.body : JSON.stringify(opts.body)) : undefined
  });
  const data = await res.json().catch(() => null);
  return { status: res.status, ok: res.ok, data };
}

async function run() {
  console.log('Starting servers for sub-agent & task breakdown testing...');
  await startAll();

  // Test 1: Verify MCP servers are registered
  const mcpRes = await api('/mcp');
  check('GET /api/mcp returns 200', mcpRes.ok);
  const servers = mcpRes.data || [];
  const subagentServer = servers.find((s) => s.name === 'subagent');
  const bgServer = servers.find((s) => s.name === 'background');

  check('subagent server is registered and connected', subagentServer?.status === 'connected');
  check('subagent exposes 2 tools', subagentServer?.tools?.length === 2);
  check('background server is registered and connected', bgServer?.status === 'connected');
  check('background exposes 4 tools', bgServer?.tools?.length === 4);

  // Test 2: Create a conversation with workdir
  const convRes = await api('/conversations', {
    method: 'POST',
    body: { title: 'Subagent Test', workdir: workDir, approval_mode: 'auto' }
  });
  check('Conversation created', convRes.ok && convRes.data?.id);
  const convId = convRes.data.id;

  // Test 3: Send chat message and listen for SSE stream
  const chatRes = await api('/chat', {
    method: 'POST',
    body: {
      conversation_id: convId,
      content: 'Break down task and run subagent',
      use_tools: true
    }
  });
  check('POST /api/chat started generation', chatRes.ok && chatRes.data?.running === true);

  // Connect to SSE stream and collect events
  const streamRes = await fetch(`${BASE}/api/chat/stream?conversation_id=${convId}`);
  check('SSE stream connection accepted', streamRes.ok);

  const reader = streamRes.body.getReader();
  const decoder = new TextDecoder();
  let buffer = '';
  const events = [];

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    const lines = buffer.split('\n\n');
    buffer = lines.pop();

    for (const block of lines) {
      let eventType = 'message';
      let eventData = null;
      for (const line of block.split('\n')) {
        if (line.startsWith('event: ')) eventType = line.slice(7).trim();
        else if (line.startsWith('data: ')) {
          try { eventData = JSON.parse(line.slice(6)); } catch { eventData = line.slice(6); }
        }
      }
      if (eventData) events.push({ event: eventType, data: eventData });
    }

    if (events.some((e) => e.event === 'done')) break;
  }

  // Test 4: Verify task_plan event was emitted
  const planEvent = events.find((e) => e.event === 'task_plan');
  check('task_plan event emitted to client', !!planEvent);
  check('task_plan has step_1', planEvent?.data?.tasks?.[0]?.id === 'step_1');

  // Test 5: Verify subagent execution lifecycle events
  const startEvent = events.find((e) => e.event === 'subagent_start');
  check('subagent_start event emitted', !!startEvent);
  check('subagent_start contains workspace', startEvent?.data?.workspace?.includes('sub_workspace'));

  const toolCallEvent = events.find((e) => e.event === 'subagent_tool_call');
  check('subagent_tool_call event emitted', !!toolCallEvent && toolCallEvent?.data?.name === 'files__write_file');

  const doneEvent = events.find((e) => e.event === 'subagent_done');
  check('subagent_done event emitted with summary', !!doneEvent && !!doneEvent?.data?.summary);
  check('subagent_done includes files_modified array with edited file', Array.isArray(doneEvent?.data?.files_modified) && doneEvent.data.files_modified.some((f) => f.includes('subagent-output.txt')));

  // Test 6: Verify file was created in scoped subagent workspace
  const expectedFile = path.join(workDir, 'sub_workspace', 'subagent-output.txt');
  check('Subagent created file in scoped workspace directory', fs.existsSync(expectedFile));
  if (fs.existsSync(expectedFile)) {
    const fileContent = fs.readFileSync(expectedFile, 'utf8');
    check('File content matches subagent output', fileContent === 'Generated by subagent.');
  }

  // Test 7: Test Steering API
  const steerRes = await api('/chat/steer', {
    method: 'POST',
    body: {
      conversation_id: convId,
      content: 'Focus only on authentication module'
    }
  });
  check('POST /api/chat/steer endpoint accepts steering guidance', steerRes.ok);

  // Test 8: Test Background Tasks REST endpoints
  const bgListRes = await api('/tasks');
  check('GET /api/tasks returns 200 with tasks array', bgListRes.ok && Array.isArray(bgListRes.data?.tasks));

  console.log(`\nSub-agent test results: ${passed} passed, ${failed} failed.`);
  if (failed > 0) process.exit(1);
}

run()
  .catch((e) => {
    console.error('Test execution failed:', e);
    process.exit(1);
  })
  .finally(() => {
    cleanup();
  });

